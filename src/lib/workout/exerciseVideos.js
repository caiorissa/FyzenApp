function normalize(value = "") {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function getExerciseVideoUrl(exercise) {
  if (exercise && typeof exercise === "object" && exercise.videoUrl)
    return exercise.videoUrl;

  const rawName =
    typeof exercise === "object" ? exercise?.name : String(exercise || "");
  const name = String(rawName)
    .replace(/\s*[–—-]\s*\d+\s*x\s*\d+(?:\s*[-–]\s*\d+)?(?:\s*.*)?$/i, "")
    .replace(/\s*[–—-]\s*\d+\s*(?:reps?|s|segundos?|min(?:utos?)?)\b.*$/i, "")
    .trim();
  const key = normalize(name);
  const aliases = {
    "abdominal normal": "Abdominal tradicional",
    "abdominal reto": "Abdominal tradicional",
    "agachamento com barra livre": "Agachamento com barra",
    "desenvolvimento com halter": "Desenvolvimento com halteres",
    "puxada alta com o peso do corpo": "Barra fixa",
    "puxada alta com peso do corpo": "Barra fixa",
    "remada com o triangulo na polia": "Remada baixa",
    "rosca alternada com halteres": "Rosca alternada",
    "remada com triangulo na polia": "Remada baixa",
    "supino inclinado com halter": "Supino inclinado com halteres",
    "supino reto com barra": "Supino reto",
    "triceps da cordinha": "Tríceps corda",
    "voador costas": "Voador inverso",
    "voador (costas)": "Voador inverso",
  };
  const canonicalName = aliases[key];
  const entry = Object.entries(EXERCISE_VIDEO_LINKS).find(
    ([exerciseName]) => normalize(exerciseName) === key,
  ) || (canonicalName ? [canonicalName, EXERCISE_VIDEO_LINKS[canonicalName]] : null);
  return entry?.[1] || "";
}

export function getLocalExerciseVideoUrl(videoUrl) {
  return /^\/videos\/exercises\/[a-z0-9-]+\.mp4$/i.test(String(videoUrl || ""))
    ? videoUrl
    : "";
}

export function getYouTubeEmbedUrl(videoUrl) {
  try {
    const url = new URL(videoUrl);
    const host = url.hostname.toLowerCase().replace(/^www\./, "");
    let videoId = "";

    if (host === "youtu.be") {
      videoId = url.pathname.split("/").filter(Boolean)[0] || "";
    } else if (
      host === "youtube.com" ||
      host === "m.youtube.com" ||
      host === "youtube-nocookie.com"
    ) {
      if (url.pathname === "/watch") videoId = url.searchParams.get("v") || "";
      else if (/^\/(embed|shorts)\//.test(url.pathname))
        videoId = url.pathname.split("/")[2] || "";
    }

    if (!/^[\w-]{11}$/.test(videoId)) return "";
    return `https://www.youtube-nocookie.com/embed/${videoId}?playsinline=1`;
  } catch {
    return "";
  }
}
